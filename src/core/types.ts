/**
 * 统一节点数据模型。
 *
 * 整个项目的核心抽象是这一句：**所有上游订阅先被解析成 `ProxyNode`，所有客户端格式
 * 再从 `ProxyNode` 生成**。解析器有 N 个、生成器有 M 个，但两侧只需各自面对这一个模型，
 * 而不是 N×M 种两两转换。
 *
 * `ProxyNode` 是**判别联合**（discriminated union），以 `type` 字段区分。这不是为了好看：
 * 各协议的字段差异极大（trojan 用 password、vmess 用 uuid+alterId、ssr 还多两层混淆参数），
 * 用一个"字段全都可选"的大对象来装，编译器就再也帮不上忙了——把 trojan 的密码当成
 * vmess 的 UUID 读出来，这类错误只会在用户导入配置失败时才被发现。
 *
 * 本文件属于 core 纯函数层：只有类型与常量，没有任何 IO。
 */

// ─────────────────────────────────────────────────────────────
//  协议与传输层
// ─────────────────────────────────────────────────────────────

/** v1 支持解析的代理协议。新增协议时同步更新 {@link PROXY_TYPES}。 */
export type ProxyType = 'vmess' | 'vless' | 'trojan' | 'ss' | 'ssr' | 'hysteria2' | 'tuic';

/** 运行时可枚举的协议列表（类型层面的 `ProxyType` 无法在运行时遍历）。 */
export const PROXY_TYPES: readonly ProxyType[] = [
  'vmess',
  'vless',
  'trojan',
  'ss',
  'ssr',
  'hysteria2',
  'tuic',
] as const;

export function isProxyType(v: string): v is ProxyType {
  return (PROXY_TYPES as readonly string[]).includes(v);
}

/**
 * 传输层。
 *
 * 注意 `h2` 与 `http` 是两回事：`h2` 指 HTTP/2 传输（Clash 写作 `h2`），
 * `http` 指伪装成 HTTP/1.1 的 TCP 传输（Clash 写作 `network: http`）。
 * 上游订阅里两者常被混用，解析时需要按来源格式区分。
 */
export type Network = 'tcp' | 'ws' | 'grpc' | 'h2' | 'http' | 'quic';

export interface WsOptions {
  path?: string;
  /** 常见的只有 Host 一项，但协议允许任意头，故用 Record。 */
  headers?: Record<string, string>;
  /** WebSocket 早期数据（0-RTT）。Clash.Meta 的 `max-early-data`。 */
  maxEarlyData?: number;
  earlyDataHeaderName?: string;
}

export interface GrpcOptions {
  serviceName?: string;
  /** `gun` 为单路复用，`multi` 为多路。省略时按客户端默认值处理。 */
  mode?: 'gun' | 'multi';
}

export interface H2Options {
  path?: string;
  host?: string[];
}

export interface HttpOptions {
  method?: string;
  path?: string[];
  headers?: Record<string, string[]>;
}

/**
 * 传输层配置。
 *
 * 之所以把各传输的选项分开成 `ws` / `grpc` / `h2` / `http` 子对象而不是平铺，
 * 是因为不同传输的 `path` 语义并不相同（ws 的 path 是字符串，http 的 path 是字符串数组），
 * 平铺会导致字段互相污染。
 */
export interface Transport {
  network: Network;
  ws?: WsOptions;
  grpc?: GrpcOptions;
  h2?: H2Options;
  http?: HttpOptions;
}

/** REALITY 参数。只有 VLESS 会用到。 */
export interface RealityOptions {
  /** 服务端公钥（URI 里的 `pbk`）。 */
  publicKey: string;
  /** 短 ID（URI 里的 `sid`）。可为空字符串，含义与缺省不同，故保留空串。 */
  shortId?: string;
  /** 爬虫路径（URI 里的 `spx`），实际很少用到。 */
  spiderX?: string;
}

export interface TlsOptions {
  enabled: boolean;
  /** SNI / servername。缺省时客户端一般回落到 server 字段。 */
  sni?: string;
  alpn?: string[];
  /** uTLS 指纹，如 `chrome` / `firefox` / `safari`。Clash.Meta 的 `client-fingerprint`。 */
  fingerprint?: string;
  /** 证书指纹固定（Clash.Meta 的 `fingerprint`），与上面的 uTLS 指纹是两个东西。 */
  certFingerprint?: string;
  /** 跳过证书校验。默认 false —— 静默放行自签证书是安全问题，必须由订阅显式声明。 */
  allowInsecure?: boolean;
  reality?: RealityOptions;
}

/** Shadowsocks 插件（obfs / v2ray-plugin / shadow-tls 等）。 */
export interface PluginOptions {
  name: string;
  /** 插件参数原样保留。不同插件的参数集完全不同，不做归一化。 */
  opts: Record<string, string | number | boolean>;
}

