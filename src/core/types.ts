/**
 * 节点的来源与推导信息。
 *
 * 这些字段**不参与指纹计算**——它们描述"这个节点是从哪来的、我们怎么看它"，
 * 而不是"连上去需要什么"。同一台服务器出现在两个订阅里应当被识别为同一节点。
 */
export interface NodeMeta {
  /** ISO 3166-1 alpha-2 地区码（如 `HK` / `JP` / `GB`），由 region.ts 推断，可能推断不出。 */
  region?: string;
  /** 所属订阅源 id。 */
  sourceId: string;
  /** 所属订阅源显示名，供 UI 与重命名模板使用。 */
  sourceName: string;
  /** 自由标签，供过滤规则匹配。v1 由解析器写入少量自动标签（如 `reality`）。 */
  tags: string[];
}

/** Link metadata for a node generated by the chain expansion pass. */
export interface ChainLink {
  /** Final display name of the entry node. */
  viaName: string;
  /** Stable fingerprint of the entry node. */
  viaFingerprint: string;
}

/**
 * Link metadata for a node whose dial address was swapped for an IX relay entry.
 *
 * 存在的第一理由是**幂等**：改写 pass 跑第二遍时 `server` 已经是入口地址，
 * 于是会把 `tls.sni` 补成入口域名 —— 得到一个"看起来配全了、实际必然握手失败"
 * 的节点，比不改写危险得多，而且没有任何测试会自然发现它。有了这个标记，
 * 第二遍能直接认出"已经改过"并跳过。
 *
 * 附带收益：界面能显示「经 xx 中转」，`originServer` 让排障能查回原落地地址。
 */
export interface IxLink {
  /** 中转入口主机名 —— 客户端实际拨号的地址，已过 `normalizeHost`。 */
  entryHost: string;
  /** 中转入口端口，由中转平台分配。 */
  entryPort: number;
  /** 改写前的 server。排障时靠它查回真正的落地机。 */
  originServer: string;
  /** 改写前的 port。 */
  originPort: number;
}

interface BaseNode {
  /**
   * 稳定指纹，见 fingerprint.ts。
   *
   * 用作节点主键：去重靠它，"手动勾选节点"的持久化也靠它。
   * 关键性质是**节点改名不会改变指纹**——上游订阅每 12 小时刷新一次，
   * 机场随时可能把 `🇭🇰 HK-01` 改成 `🇭🇰 香港01`，如果用名字做主键，
   * 用户勾选的节点会在第一次刷新后全部失效。
   */
  fingerprint: string;
  /** 显示名，来自上游，可能被重命名规则改写。 */
  name: string;
  server: string;
  /** 1–65535。解析器负责校验范围。 */
  port: number;
  /** 是否支持 UDP 转发。上游未声明时为 undefined，由生成器决定默认值。 */
  udp?: boolean;
  meta: NodeMeta;
  /** Set only by core/chain.ts; parsers never accept upstream chain fields. */
  chain?: ChainLink;
  /** Set only by core/ix.ts; parsers never accept upstream ix fields. */
  ix?: IxLink;
}

export interface VmessNode extends BaseNode {
  type: 'vmess';
  uuid: string;
  /**
   * AlterID。现代 VMess（AEAD）恒为 0。
   * 非 0 值意味着旧版 MD5 认证，部分新客户端已不再支持，生成器需要如实传递。
   */
  alterId: number;
  /** `auto` / `aes-128-gcm` / `chacha20-poly1305` / `none` 等。 */
  cipher: string;
  transport: Transport;
  tls?: TlsOptions;
}

export interface VlessNode extends BaseNode {
  type: 'vless';
  uuid: string;
  /** XTLS 流控，如 `xtls-rprx-vision`。空值表示不启用。 */
  flow?: string;
  /** VLESS 的 encryption 目前恒为 `none`，保留字段是为了将来协议扩展。 */
  encryption?: string;
  transport: Transport;
  tls?: TlsOptions;
}

export interface TrojanNode extends BaseNode {
  type: 'trojan';
  password: string;
  transport: Transport;
  /** Trojan 本身以 TLS 为前提，故此处不可选。 */
  tls: TlsOptions;
}

export interface SsNode extends BaseNode {
  type: 'ss';
  cipher: string;
  password: string;
  plugin?: PluginOptions;
}

export interface SsrNode extends BaseNode {
  type: 'ssr';
  cipher: string;
  password: string;
  /** 协议插件，如 `auth_aes128_md5`。 */
  protocol: string;
  protocolParam?: string;
  /** 混淆插件，如 `tls1.2_ticket_auth`。 */
  obfs: string;
  obfsParam?: string;
}

export interface Hysteria2Node extends BaseNode {
  type: 'hysteria2';
  password: string;
  /** 混淆类型，目前只有 `salamander`。 */
  obfs?: string;
  obfsPassword?: string;
  /** 上下行带宽声明，如 `100 mbps`。Hysteria 的拥塞控制依赖它。 */
  up?: string;
  down?: string;
  tls: TlsOptions;
}

export interface TuicNode extends BaseNode {
  type: 'tuic';
  uuid: string;
  password: string;
  /** `cubic` / `bbr` / `new_reno`。 */
  congestionController?: string;
  /** `native` / `quic`。 */
  udpRelayMode?: string;
  tls: TlsOptions;
}

/** 统一节点模型。以 `type` 判别。 */
export type ProxyNode =
  | VmessNode
  | VlessNode
  | TrojanNode
  | SsNode
  | SsrNode
  | Hysteria2Node
  | TuicNode;

/**
 * 解析器的产出：尚未计算指纹、尚未绑定来源的"半成品"节点。
 *
 * 存在的理由是先有鸡还是先有蛋：指纹由节点内容算出，所以解析器不可能在构造节点时
 * 就填好它；而来源信息（sourceId / sourceName）只有调用方知道。
 * 由 {@link finalizeNode} 统一补齐这两部分。
 *
 * 这里用**分配式条件类型**逐个成员做 Omit。直接写 `Omit<ProxyNode, ...>` 是不行的：
 * `Omit` 内部用 `keyof`，而联合类型的 `keyof` 是各成员键的**交集**，
 * 结果会退化成只剩公共字段（name/server/port/type）的对象，
 * uuid、password 这些协议字段全部消失，判别联合也就失效了。
 */
type DistributiveDraft<T> = T extends unknown ? Omit<T, 'fingerprint' | 'meta'> : never;

export type ProxyNodeDraft = DistributiveDraft<ProxyNode>;

