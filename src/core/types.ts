/**
 * `Subscription-Userinfo` 响应头承载的流量信息。
 *
 * 这是机场订阅事实上的标准（无 RFC），形如：
 * `upload=96701335; download=143028274; total=161061273600; expire=1803225600`
 *
 * 四个字段都可能缺失：不限量套餐没有 `total`，长期套餐没有 `expire`。
 * 因此除了 upload/download 之外都是可选的。
 */
export interface TrafficInfo {
  /** 已上传字节数。 */
  upload: number;
  /** 已下载字节数。 */
  download: number;
  /** 总配额字节数。缺失表示不限量。 */
  total?: number;
  /** 到期时间，Unix 秒（注意不是毫秒）。缺失表示不过期。 */
  expire?: number;
}
