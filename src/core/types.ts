/**
 * 单条解析失败的记录。
 *
 * 解析上游订阅时**不能因为一个坏节点就整体失败**——机场经常在订阅里混入格式错误的行，
 * 或者使用我们尚未支持的协议。正确做法是跳过它、记下来、继续解析其余节点，
 * 最后把失败清单如实呈现给用户。静默吞掉会让用户以为节点数变少是服务商的问题。
 */
export interface ParseIssue {
  /** 出问题的原始内容，会被截断以免日志爆炸。 */
  raw: string;
  reason: string;
}

export interface ParseResult {
  nodes: ProxyNodeDraft[];
  issues: ParseIssue[];
}

